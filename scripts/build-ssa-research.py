#!/usr/bin/env python3
"""Turn content-import/ssa/research.json into src/lib/ssa-research.ts.

Run from the repo root:
  python3 scripts/build-ssa-research.py

research.json holds what we could verify about each chapter from public
sources (campus organization directories, chaplaincy and religious-life
pages, chapter websites, student newspapers): verbatim descriptions with
their source, dated facts, official links, the chapter's organization email,
which official page confirms its Instagram account, and roster corrections.

This script only copies it into the site, with two checks:
  - a quoted sentence containing an em or en dash is dropped (site copy rule);
  - an Instagram confirmation is kept only if the handle the official page
    lists matches the handle in ssa-instagram.ts.
"""
import json
import re

SRC = 'content-import/ssa/research.json'
OUT = 'src/lib/ssa-research.ts'


def main():
    data = json.load(open(SRC, encoding='utf-8'))
    ig = open('src/lib/ssa-instagram.ts', encoding='utf-8').read()
    handles = dict(re.findall(r'"slug": "([^"]+)",\s*"handle": "([^"]+)"', ig))
    out = {}
    for slug, e in data['chapters'].items():
        about = []
        for a in e.get('about', []):
            parts = re.split(r'(?<=[.!?])\s+', a['text'])
            kept = [p for p in parts if not re.search('[–—]', p)]
            if len(kept) != len(parts):
                print(f'{slug}: dropped {len(parts) - len(kept)} sentence(s) with a dash')
            if kept:
                about.append({**a, 'text': ' '.join(kept)})
        v = e.get('instagramVerifiedBy')
        if v and handles.get(slug, '').lower() != v['handle']:
            print(f"{slug}: official page lists @{v['handle']}, csv has @{handles.get(slug)}; not confirming")
            v = None
        out[slug] = {
            'about': about,
            'facts': e.get('facts', []),
            'links': e.get('links', []),
            'email': e.get('email'),
            'instagramVerifiedBy': v,
            'correction': e.get('correction'),
        }
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// GENERATED by scripts/build-ssa-research.py from content-import/ssa/research.json.\n')
        f.write('// Do not edit by hand: change the JSON and re-run the script.\n')
        f.write('//\n// Public, sourced information about each chapter. Quotes are verbatim.\n')
        f.write("export type Sourced = { sourceLabel: string; sourceUrl: string };\n")
        f.write('export type ChapterResearch = {\n')
        f.write('  about: ({ text: string } & Sourced)[];\n')
        f.write('  facts: ({ label: string; value: string } & Sourced)[];\n')
        f.write('  links: { label: string; url: string }[];\n')
        f.write('  email: ({ address: string } & Sourced) | null;\n')
        f.write('  instagramVerifiedBy: ({ handle: string } & Sourced) | null;\n')
        f.write('  correction: ({ school: string; city?: string; state?: string; latitude?: number; longitude?: number } & Sourced) | null;\n')
        f.write('};\n\n')
        f.write(f"export const RESEARCH_PULLED_ON = '{data['pulledOn']}';\n\n")
        f.write('export const chapterResearch: Record<string, ChapterResearch> = ')
        f.write(json.dumps(out, ensure_ascii=False, indent=2))
        f.write(';\n')
    print(f'wrote {len(out)} chapters to {OUT}')


if __name__ == '__main__':
    main()
