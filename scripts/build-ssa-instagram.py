#!/usr/bin/env python3
"""Generate src/lib/ssa-instagram.ts from content-import/ssa/ssa_instagram.csv.

Run from the repo root:  python3 scripts/build-ssa-instagram.py

Only fields the chapter pages use are emitted. Follower and post counts are
deliberately left out (not shown on the site). Profile pictures are NOT copied:
`image` is always null until USM decides on permission (see the
CHAPTER_IMAGES_ENABLED switch in src/lib/chapters.ts).
"""
import csv
import json
import re
import unicodedata

SRC = 'content-import/ssa/ssa_instagram.csv'
OUT = 'src/lib/ssa-instagram.ts'


def confidence(raw: str) -> str:
    raw = raw.strip().lower()
    if raw == 'high':
        return 'high'  # account pulled and checked: display name fits the chapter
    if raw.startswith('high'):
        return 'unverified'  # handle came from the USM page; profile was not pulled
    return 'low'  # does not look like the chapter's account (e.g. harvard)


def clean_display(name: str) -> str:
    # Drop decorative symbols and emoji (☬, 🪯, ✦ ...) for use in headings.
    kept = ''.join(c for c in name if unicodedata.category(c)[0] not in ('S', 'C'))
    return re.sub(r'\s+', ' ', kept).strip()


rows = []
with open(SRC, newline='', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        handle = r['handle'].strip().lstrip('@')
        rows.append({
            'slug': r['slug'].strip(),
            'handle': handle or None,
            'igUrl': r['ig_url'].strip() or None,
            'confidence': confidence(r['confidence']),
            'displayName': clean_display(r['display_name']) or None,
            'bio': r['bio'].strip() or None,  # quoted exactly as written on Instagram
            'pulledOn': r['counts_pulled'].strip() or None,
            'image': None,
        })

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// GENERATED by scripts/build-ssa-instagram.py from content-import/ssa/ssa_instagram.csv.\n')
    f.write('// Do not edit by hand: change the CSV and re-run the script.\n')
    f.write('//\n')
    f.write('// confidence: "high" = profile pulled and display name fits the chapter;\n')
    f.write('// "unverified" = handle taken from the USM page, profile not pulled;\n')
    f.write('// "low" = account does not look like the chapter\'s. Only "high" is linked.\n')
    f.write("export type ChapterInstagram = {\n  slug: string;\n  handle: string | null;\n  igUrl: string | null;\n")
    f.write("  confidence: 'high' | 'unverified' | 'low';\n  displayName: string | null;\n  bio: string | null;\n")
    f.write("  pulledOn: string | null;\n  /** Profile image path. Always null until image use is approved. */\n  image: string | null;\n};\n\n")
    f.write('export const chapterInstagram: Record<string, ChapterInstagram> = ')
    f.write(json.dumps({r['slug']: r for r in rows}, ensure_ascii=False, indent=2))
    f.write(';\n')

print(f'wrote {len(rows)} chapters to {OUT}')
